import type {
  TrainingEquipment,
  TrainingExercise,
  TrainingMuscle,
} from './training';

type ExerciseDefinition = [
  id: string,
  name: string,
  aliases: string[],
  primary: TrainingMuscle[],
  secondary?: TrainingMuscle[]
];

function exercises(
  equipment: TrainingEquipment,
  definitions: ExerciseDefinition[]
): TrainingExercise[] {
  return definitions.map(([id, name, aliases, primary, secondary = []]) => ({
    id,
    name,
    aliases,
    primary,
    secondary,
    equipment,
  }));
}

